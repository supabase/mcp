/**
 * The local HTTP server on a mocked Supabase platform, for end-to-end work on
 * MCP Apps without a Supabase account or real data. The Management API and
 * content API are the test mocks (msw); each project database is PGlite.
 *
 *   pnpm dev:mock -- --apps-dir ../../../supabase/apps/mcp-apps/dist/v1
 *
 * Connect with the access token printed on startup. Logs are synthetic.
 */
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { http, HttpResponse } from 'msw';

import type { AppsOptions } from '../src/tools/apps/index.js';
import { startLocalHttpEntry } from '../src/transports/local-http-entry.js';
import {
  ACCESS_TOKEN,
  API_URL,
  createOrganization,
  createProject,
  setupMockApis,
} from '../test/mocks.js';

const { values } = parseArgs({
  options: {
    port: { type: 'string', default: '3111' },
    'apps-dir': { type: 'string' },
    'apps-url': { type: 'string' },
    'app-link': { type: 'string' },
  },
});

const assets = values['apps-dir']
  ? { dir: resolve(values['apps-dir']) }
  : values['apps-url']
    ? { url: values['apps-url'] }
    : undefined;
const apps: AppsOptions | undefined = assets && {
  assets,
  appLinkBase: values['app-link'],
};

const mockServer = setupMockApis({ expectedUserAgent: null });
// Let everything the mocks do not cover (e.g. linked surface assets) through.
mockServer.close();
mockServer.listen({ onUnhandledRequest: 'bypass' });

const SOURCES = [
  'edge_logs',
  'postgres_logs',
  'auth_logs',
  'function_edge_logs',
];
const PATHS = [
  '/rest/v1/orders',
  '/rest/v1/products',
  '/auth/v1/token',
  '/functions/v1/checkout',
];

/** Plausible logs for the last day: hourly traffic for overview charts, events otherwise. */
function syntheticLogs(sql: string) {
  const now = Date.now();
  if (/\brequests\b/.test(sql) && /\berrors\b/.test(sql)) {
    return Array.from({ length: 24 }, (_, index) => {
      const requests = 400 + Math.round(300 * Math.sin(index / 3) ** 2);
      const errors = index % 7 === 3 ? 42 : Math.round(requests * 0.01);
      return {
        // Complete hours of the last day, as the overview query buckets them.
        timestamp:
          Math.floor(now / 3_600_000) * 3_600_000 - (24 - index) * 3_600_000,
        requests,
        responses: requests,
        errors,
      };
    });
  }
  return Array.from({ length: 60 }, (_, index) => {
    const status = index % 11 === 0 ? 500 : index % 5 === 0 ? 404 : 200;
    const source = SOURCES[index % SOURCES.length];
    return {
      timestamp: new Date(now - index * 47_000).toISOString(),
      source,
      severity_text: status >= 500 ? 'ERROR' : 'INFO',
      level: status >= 500 ? 'error' : status >= 400 ? 'warning' : 'info',
      status: String(status),
      method: index % 3 === 0 ? 'POST' : 'GET',
      path: PATHS[index % PATHS.length],
      event_message:
        status >= 500
          ? 'upstream request failed: connection reset'
          : `${index % 3 === 0 ? 'POST' : 'GET'} ${PATHS[index % PATHS.length]} ${status}`,
    };
  });
}

mockServer.use(
  http.get(
    `${API_URL}/v1/projects/:projectId/analytics/endpoints/logs`,
    ({ request }) => {
      const sql = new URL(request.url).searchParams.get('sql') ?? '';
      return HttpResponse.json({ result: syntheticLogs(sql) });
    }
  )
);

const organization = await createOrganization({
  name: 'Acme',
  plan: 'pro',
  allowed_release_channels: ['ga'],
});

const shop = await createProject({
  name: 'acme-shop',
  region: 'us-east-1',
  organization_id: organization.id,
});
const analytics = await createProject({
  name: 'acme-analytics',
  region: 'eu-west-1',
  organization_id: organization.id,
});
for (const project of [shop, analytics]) project.status = 'ACTIVE_HEALTHY';

await shop.db.exec(`
  create table public.customers (
    id bigint generated by default as identity primary key,
    email text not null unique,
    name text,
    created_at timestamptz not null default now()
  );
  create table public.products (
    id bigint generated by default as identity primary key,
    name text not null,
    price numeric(10, 2) not null,
    in_stock boolean not null default true
  );
  create table public.orders (
    id bigint generated by default as identity primary key,
    customer_id bigint references public.customers (id),
    product_id bigint references public.products (id),
    quantity int not null default 1,
    status text not null default 'pending',
    created_at timestamptz not null default now()
  );
  create table public.order_events (
    order_id bigint not null,
    seq int not null,
    note text,
    primary key (order_id, seq)
  );
  alter table public.customers enable row level security;
  insert into public.customers (email, name)
    select 'user' || n || '@example.com', 'Customer ' || n from generate_series(1, 40) n;
  insert into public.products (name, price, in_stock)
    select 'Product ' || n, (n * 3.5)::numeric(10, 2), n % 4 <> 0 from generate_series(1, 25) n;
  insert into public.orders (customer_id, product_id, quantity, status, created_at)
    select 1 + n % 40, 1 + n % 25, 1 + n % 3,
      (array['pending', 'paid', 'shipped', 'refunded'])[1 + n % 4],
      now() - (n || ' hours')::interval
    from generate_series(1, 300) n;
  insert into public.order_events select 1 + n % 50, n, 'event ' || n from generate_series(1, 120) n;
`);
await analytics.db.exec(`
  create table public.page_views (
    id bigint generated by default as identity primary key,
    path text not null,
    viewed_at timestamptz not null default now()
  );
  insert into public.page_views (path, viewed_at)
    select '/page/' || (n % 12), now() - (n || ' minutes')::interval from generate_series(1, 500) n;
`);

const entry = await startLocalHttpEntry({
  port: Number(values.port),
  apiUrl: API_URL,
  apps,
});
console.error(`Mock Supabase MCP server listening on ${entry.url}`);
console.error(
  `Access token: ${ACCESS_TOKEN}  (projects: ${shop.id}, ${analytics.id})`
);
